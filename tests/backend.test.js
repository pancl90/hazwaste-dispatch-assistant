'use strict';
const test=require('node:test');const assert=require('node:assert/strict');const fs=require('node:fs');const os=require('node:os');const path=require('node:path');
const {createApplication}=require('../backend/application');
test('API: auth, organization/owner isolation, CRUD, idempotency, conflicts, migration and privacy',async t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'dispatch-test-'));
 const app=createApplication({dataDir:dir,key:Buffer.alloc(32,7),allowHttp:true});
 t.after(async()=>{await app.close();fs.rmSync(dir,{recursive:true,force:true})});
 await app.addUser({username:'alice',password:'Example-test-only-321!',orgId:'org-a',role:'admin'});
 await app.addUser({username:'bob',password:'Example-test-only-322!',orgId:'org-a',role:'member'});
 await app.addUser({username:'eve',password:'Example-test-only-323!',orgId:'org-b',role:'admin'});
 await app.listen(0);const base='http://127.0.0.1:'+app.port;
 async function call(route,method='GET',body,token){const r=await fetch(base+route,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:body===undefined?undefined:JSON.stringify(body)});return {status:r.status,body:await r.json()}}
 const login=await call('/api/auth/login','POST',{username:'alice',password:'Example-test-only-321!'});assert.equal(login.status,200);const a=login.body.token;
 const b=(await call('/api/auth/login','POST',{username:'bob',password:'Example-test-only-322!'})).body.token;
 const e=(await call('/api/auth/login','POST',{username:'eve',password:'Example-test-only-323!'})).body.token;
 assert.equal((await call('/api/tasks')).status,401);
 const task={id:'task-test',client:'虚构客户',status:'待安排',pickupDate:'2026-11-02',rawMessage:'虚构测试消息'};
 const create={record:task,baseRevision:0,operationId:'op-test-create'};
 const saved=await call('/api/tasks/task-test','PUT',create,a);assert.equal(saved.status,200);assert.equal(saved.body.record.revision,1);
 assert.equal((await call('/api/tasks/task-test','PUT',create,a)).body.record.revision,1);
 assert.equal((await call('/api/tasks', 'GET',undefined,b)).body.items.length,0);
 assert.equal((await call('/api/tasks/task-test','GET',undefined,b)).status,404);
 assert.equal((await call('/api/tasks/task-test','GET',undefined,e)).status,404);
 assert.equal((await call('/api/tasks/task-test','PUT',{...create,operationId:'op-stale',record:{...task,client:'修改'}},a)).status,409);
 assert.equal((await call('/api/tasks/task-test','PUT',{record:{...task,status:'非法状态'},baseRevision:1,operationId:'op-invalid'},a)).status,400);
 const migration={batchId:'migration-test',tasks:[{...task,id:'migration-new',rawMessage:'另一条主动迁移测试'}],customers:[]};
 assert.equal((await call('/api/migrations','POST',migration,b)).status,403);
 assert.equal((await call('/api/migrations/migration-test/rollback','POST',{},b)).status,403);
 assert.equal((await call('/api/management/authorize','POST',{action:'backup'},b)).status,403);
 assert.equal((await call('/api/management/authorize','POST',{action:'backup'},a)).status,200);
 const imported=await call('/api/migrations','POST',migration,a);assert.equal(imported.status,200);assert.equal(imported.body.created.length,1);
 assert.equal((await call('/api/migrations','POST',migration,a)).body.created.length,1);
 assert.equal((await call('/api/migrations/migration-test/rollback','POST',{},a)).status,200);
 assert.equal((await call('/api/tasks/migration-new','GET',undefined,a)).status,404);
 assert.equal((await call('/api/wechat/subscription/challenge','POST',{},a)).status,503);
 assert.equal((await call('/api/audit','GET',undefined,a)).status,200);
 assert.equal((await fetch(base+'/data/store.enc')).status,404);
 assert.equal((await fetch(base+'/backend/application.js')).status,404);
 assert.ok(!fs.readFileSync(path.join(dir,'store.enc'),'utf8').includes('虚构客户'));
 assert.equal((await call('/api/tasks/task-test','DELETE',{baseRevision:1,operationId:'op-delete'},a)).status,200);
 assert.ok(!JSON.stringify(app.store.state.tasks).includes('虚构客户'));
 assert.ok(!JSON.stringify(app.store.state.operations).includes('虚构客户'));
 assert.equal((await call('/api/sync?kind=tasks','GET',undefined,a)).body.items.some(x=>x.id==='task-test'&&x.deleted),true);
});
